CREATE TABLE IF NOT EXISTS system.cdnsell_usage_windows (
 id BIGINT UNSIGNED NOT NULL PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL, domain_id BIGINT UNSIGNED NOT NULL,
 window_start DATETIME NOT NULL, window_end DATETIME NOT NULL,
 confirmed_bytes BIGINT UNSIGNED NOT NULL DEFAULT 0,
 overage_bytes BIGINT UNSIGNED NOT NULL DEFAULT 0,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY uk_cdn_usage_window(domain_id,window_start)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS system.cdnsell_usage_allocations (
 window_id BIGINT UNSIGNED NOT NULL, batch_id BIGINT UNSIGNED NOT NULL,
 consumed_bytes BIGINT UNSIGNED NOT NULL,
 PRIMARY KEY(window_id,batch_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS system.cdnsell_usage_cursors (
 domain_id BIGINT UNSIGNED NOT NULL PRIMARY KEY,
 confirmed_until DATETIME NOT NULL,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
ALTER TABLE system.cdnsell_tasks ADD COLUMN lease_until DATETIME NULL;
ALTER TABLE system.cdnsell_config_tasks ADD COLUMN lease_until DATETIME NULL, ADD COLUMN next_run_at DATETIME NULL;
ALTER TABLE system.cdnsell_refresh_tasks ADD COLUMN lease_until DATETIME NULL;
CREATE TABLE IF NOT EXISTS system.cdnsell_admin_audits (
 id BIGINT UNSIGNED NOT NULL PRIMARY KEY, admin_id BIGINT UNSIGNED NOT NULL,
 action VARCHAR(40) NOT NULL, payload JSON NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
